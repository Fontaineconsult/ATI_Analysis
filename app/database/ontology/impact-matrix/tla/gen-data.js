// Writes ReviewerData.tla from the tables in review-matrix.js, so the spec and the model
// share one copy of the grid, the floors, the evidence ranks and the TAAP standard.
// Run: node app/database/ontology/impact-matrix/tla/gen-data.js
const fs = require('fs');
const path = require('path');
const M = require(path.join(__dirname, '..', 'review-matrix.js'));

const cases = (pairs) => pairs.map(([guard, value]) => `${guard} -> ${value}`).join('\n    [] ');
const str = (s) => `"${s}"`;

const grade = [];
for (const l of M.LEVELS) for (const s of ['S0', 'S1', 'S2', 'S3']) grade.push([`l = ${str(l)} /\\ s = ${str(s)}`, str(M.GRID[l][s].grade)]);
const floor = M.LEVELS.map((l) => [`l = ${str(l)}`, M.EVIDENCE_LIMITS.floor[l]]);
const evRank = M.EVIDENCE.map((e) => [`e = ${str(e.id)}`, e.rank]);
const required = M.CALIBRATION.taapStandard.required.map((n, p) => [`p = ${p}`, n]);

const out = `---- MODULE ReviewerData ----
\\* Generated by gen-data.js from review-matrix.js, matrix version ${M.MATRIX_VERSION}. Do not edit.
EXTENDS Naturals

\\* The grid: the risk grade by exposure level and worst severity.
Grade(l, s) ==
  CASE ${cases(grade)}

\\* The Veracity floor by exposure level.
Floor(l) ==
  CASE ${cases(floor)}

\\* The rank of each evidence level.
EvRank(e) ==
  CASE ${cases(evRank)}

\\* The TAAP standard: requirements a plan must meet at each pressure.
Required(p) ==
  CASE ${cases(required)}

TaapCount == ${M.TAAP_REQUIREMENTS.length}
====
`;
const target = path.join(__dirname, 'ReviewerData.tla');
fs.writeFileSync(target, out);
console.log('wrote', target);
