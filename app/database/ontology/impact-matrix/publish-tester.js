// Copies the review tester into the public reports blueprint, which serves it at
// /ati/reports/public/review-matrix/. The files here stay the source: the build scripts, the
// email checks and the TLA+ conformance check all read them, so the published folder is a
// generated copy that nobody edits. deployment/deploy_to_dprc_server.cmd runs this before it
// copies app\ to the server.
//   node app/database/ontology/impact-matrix/publish-tester.js
const fs = require('fs');
const path = require('path');

const FILES = ['review-matrix-tester.html', 'review-matrix-tester.css', 'review-matrix-tester.js', 'review-matrix.js', 'review-emails.js'];
const OUT = path.resolve(__dirname, '../../../public_reports/static/review-matrix');

fs.mkdirSync(OUT, { recursive: true });
// Clear what an earlier publish left, so a file dropped from the list does not linger on the server.
for (const f of fs.readdirSync(OUT)) if (f !== 'README.md') fs.rmSync(path.join(OUT, f));
for (const f of FILES) fs.copyFileSync(path.join(__dirname, f), path.join(OUT, f));

// The page may load only the files published with it, plus the pinned CDN libraries.
const html = fs.readFileSync(path.join(OUT, 'review-matrix-tester.html'), 'utf8');
const local = [...html.matchAll(/(?:src|href)="([^"#:]+)"/g)].map((m) => m[1]);
const missing = local.filter((f) => !FILES.includes(f));
if (missing.length) {
  console.error(`The tester references files that are not published: ${missing.join(', ')}. Add them to FILES.`);
  process.exit(1);
}

fs.writeFileSync(path.join(OUT, 'README.md'), `# Review matrix tester, published copy

Generated by \`app/database/ontology/impact-matrix/publish-tester.js\`. Do not edit these
files. Edit the sources in \`app/database/ontology/impact-matrix/\` and run the script, or
deploy with \`deployment/deploy_to_dprc_server.cmd\`, which runs it.

Served at \`/ati/reports/public/review-matrix/\` by \`app/public_reports/__init__.py\`.
`);
console.log(`published ${FILES.length} files to ${path.relative(process.cwd(), OUT) || OUT}`);
