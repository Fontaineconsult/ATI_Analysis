"""
Emit an idempotent batch Cypher file that records a run's snapshots as Metrics.

The reviewed path for loading snapshots into the live graph: the file is read,
validated with run_file, and executed with run_file --execute. It writes what
store.save_snapshot writes through the queries layer, built from the same
snapshot_metric_dict:

  1. Metric (MERGE by composite_key, the unique index), with unique_id in the
     app's format and value_dict as the JSON string JSONProperty stores
  2. (Metric)-[:measured_in_year]->(AcademicYear)
  3. (Tracking)-[:has_metric {included_in_years, excluded_from_years,
     added_date, modified_date}]->(Metric), as assign_documentation_to_implementation sets it

Every string literal sits on one line because run_file splits a file on ';' at
end of line and drops lines that start with '//'.

    python -m app.services.pope_tech_integration.emit_cypher <run_dir> <academic_year> <out.cypher>
"""
import json
import sys
from pathlib import Path

from app.services.pope_tech_integration import config
from app.services.pope_tech_integration.fetch import read_snapshots
from app.services.pope_tech_integration.snapshot import snapshot_metric_dict


def q(value) -> str:
    """A Cypher string literal on one line, or null."""
    if value is None:
        return "null"
    text = str(value).replace("\\", "\\\\").replace("'", "\\'")
    return "'" + text.replace("\r", "\\r").replace("\n", "\\n") + "'"


def statement(metric: dict, tracking_title: str) -> str:
    year = metric["academic_year"]
    return f"""
// {metric['composite_key']} on {tracking_title}
MATCH (t:Tracking {{title: {q(tracking_title)}}})
MATCH (ay:AcademicYear {{name: {q(year)}}})
MERGE (m:Metric {{composite_key: {q(metric['composite_key'])}}})
  ON CREATE SET
    m.unique_id = replace(randomUUID(), '-', ''),
    m.name = {q(metric['name'])},
    m.metric_type = {q(metric['metric_type'])},
    m.description = {q(metric['description'])},
    m.single_value = {q(metric['single_value'])},
    m.value_dict = {q(json.dumps(metric['value_dict']))},
    m.value_schema = {q(metric['value_schema'])},
    m.measured_on = date({q(metric['measured_on'])}),
    m.include_in_report = true
MERGE (m)-[:measured_in_year]->(ay)
MERGE (t)-[r:has_metric]->(m)
  ON CREATE SET
    r.included_in_years = [{q(year)}],
    r.excluded_from_years = [],
    r.added_date = date(),
    r.modified_date = date();"""


def build(run_dir: Path, academic_year: str, tracking_titles: dict = None) -> tuple:
    """(file text, list of composite keys). Snapshots without data are left out."""
    titles = config.TRACKING_TITLES if tracking_titles is None else tracking_titles
    parts, keys, skipped = [], [], []
    for snap in read_snapshots(run_dir):
        campus = (snap.get("org") or {}).get("campus")
        if not snap.get("has_data"):
            skipped.append(f"{campus} {snap.get('as_of')}: no scan data")
            continue
        if campus not in titles:
            skipped.append(f"{campus} {snap.get('as_of')}: no Tracking configured")
            continue
        metric = snapshot_metric_dict(snap, academic_year)
        parts.append(statement(metric, titles[campus]))
        keys.append(metric["composite_key"])

    header = [
        "// Pope Tech WAVE scan snapshots recorded as Metrics on each campus's Tracking.",
        f"// Generated by app/services/pope_tech_integration/emit_cypher.py from run {Path(run_dir).name}.",
        f"// Academic year: {academic_year}. Idempotent: MERGE on Metric.composite_key.",
    ]
    header += [f"// Left out: {s}" for s in skipped]
    return "\n".join(header) + "\n" + "".join(parts) + "\n", keys


def main(argv):
    if len(argv) != 3:
        print(__doc__.strip().splitlines()[-1].strip())
        return 2
    run_dir, academic_year, out_path = Path(argv[0]), argv[1], Path(argv[2])
    text, keys = build(run_dir, academic_year)
    out_path.write_text(text, encoding="utf-8")
    print(f"wrote {len(keys)} statements to {out_path}")
    for key in keys:
        print(f"  {key}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
